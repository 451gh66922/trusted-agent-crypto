#!/usr/bin/env bash
# ==============================================================================
# 竞赛现场答辩演示专用脚本 (≤ 5 分钟全链路自证)
# 演示主线：正常 SoftSE 授权 -> 拔卡/卸载阻断 -> 密钥使用点策略硬门拦截
# ==============================================================================

set -e

# 终端彩色输出定义
GREEN="\033[1;32m"
RED="\033[1;31m"
YELLOW="\033[1;33m"
CYAN="\033[1;36m"
BOLD="\033[1m"
RESET="\033[0m"

clear
echo -e "${BOLD}${CYAN}======================================================================${RESET}"
echo -e "${BOLD}${CYAN}  基于安全芯片的 AI Agent 可信授权防御系统 (现场实机演示)${RESET}"
echo -e "${BOLD}${CYAN}======================================================================${RESET}"
echo -e "运行环境：本地离线容器 (Keycloak 26.4 + 本地安全后端 + 资源服务器 RS)"
echo -e "标准依据：RFC 9449 (OAuth 2.0 DPoP) + 统一 CryptoBackend 接口规范\n"

# ------------------------------------------------------------------------------
# 阶段 1: 正常端到端闭环链路
# ------------------------------------------------------------------------------
echo -e "${BOLD}${GREEN}[演示 1/3] 正常授权主链路：SoftSE 安全后端 -> Keycloak -> 资源服务 RS${RESET}"
echo -e "👉 ${YELLOW}预期目标${RESET}：密钥不出后端，安全签发 Proof，成功获取 DPoP Token 并读取核心业务数据。"
read -p "按回车键 [Enter] 开始执行演示 1..." -r
echo ""

AUTH_BACKEND=soft_se python3 examples/demo_ok.py

echo -e "\n${BOLD}${GREEN}✔ [演示 1 验证通过]${RESET}：全链路 200 OK，证明协议真实可用、公钥指纹绑定生效！\n"
echo -e "${CYAN}----------------------------------------------------------------------${RESET}\n"

# ------------------------------------------------------------------------------
# 阶段 2: 拔卡 / 卸载模拟演示 (物理记忆点)
# ------------------------------------------------------------------------------
echo -e "${BOLD}${YELLOW}[演示 2/3] 授权根可控性：安全后端拔除 / 卸载模拟 (拔卡即失效)${RESET}"
echo -e "👉 ${YELLOW}预期目标${RESET}：在授权流程中模拟安全硬件被物理拔出，签名操作必须被底层硬阻断。"
read -p "按回车键 [Enter] 开始执行演示 2..." -r
echo ""

set +e  # 预期会报错，临时关闭严格退出
AUTH_BACKEND=unplugged python3 examples/demo_ok.py
EXIT_CODE=$?
set -e

if [ $EXIT_CODE -ne 0 ]; then
    echo -e "\n${BOLD}${GREEN}✔ [演示 2 验证通过]${RESET}：捕获底层 HARDWARE_NOT_PRESENT 异常！"
    echo -e "💡 ${BOLD}评委证据点${RESET}：证明授权根完全受控！一旦芯片离线，Agent 持续性风险瞬间化解！\n"
else
    echo -e "\n${BOLD}${RED}❌ [演示 2 异常] 未能有效拦截拔除状态！${RESET}\n"
    exit 1
fi
echo -e "${CYAN}----------------------------------------------------------------------${RESET}\n"

# ------------------------------------------------------------------------------
# 阶段 3: 密钥使用点策略硬门 (冲奖核心增量)
# ------------------------------------------------------------------------------
echo -e "${BOLD}${RED}[演示 3/3] 防 Prompt 诱导与越权滥用：密钥使用点策略门 (PolicyGate)${RESET}"
echo -e "👉 ${YELLOW}预期目标${RESET}：模拟 Agent 遭遇越狱注入试图越权调用恶意接口，防御发生在私钥签名点，不靠 Prompt！"
read -p "按回车键 [Enter] 开始执行演示 3..." -r
echo ""

python3 examples/test_policy_gate.py

echo -e "\n${BOLD}${GREEN}✔ [演示 3 验证通过]${RESET}：精准抛出 POLICY_DENIED_RECIPIENT，非白名单目标硬拦截成功！"
echo -e "💡 ${BOLD}评委证据点${RESET}：证明与传统 Prompt 软防御的本质差异——恶意诱导无法突破密钥层硬约束！\n"

# ------------------------------------------------------------------------------
# 总结收官
# ------------------------------------------------------------------------------
echo -e "${BOLD}${CYAN}======================================================================${RESET}"
echo -e "${BOLD}${GREEN}🎉 现场实机演示全部圆满完成！全部防御结论均具备确凿日志与错误码支撑！${RESET}"
echo -e "${BOLD}${CYAN}======================================================================${RESET}"
